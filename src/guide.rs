//! 図鑑の読みもの。個別の紹介、なかまの体とくらし、観察のコツ、関東で会える場所を分けて読む。
//! 日本語の追加本文は ja(...) で明示し、読み辞書の検査にも含める。
use crate::earth::SPOTS;
use crate::lang::Lang;
use crate::life::{self, Art, Beh, SPECIES};

pub struct Section {
    pub title: &'static str,
    pub body: String,
}

fn ja(text: &'static str) -> &'static str {
    text
}

fn local(text: crate::lang::L, language: Lang) -> &'static str {
    match language {
        Lang::Ja => text.0,
        Lang::En => text.1,
        Lang::Zh => text.2,
    }
}

pub fn sections(e: usize, language: Lang) -> Vec<Section> {
    let sp = &SPECIES[e];
    let mut result = vec![Section {
        title: match language {
            Lang::Ja => "まずは知ろう",
            Lang::En => "Meet this insect",
            Lang::Zh => "先来认识",
        },
        body: format!("{}\n\n{}", local(sp.desc, language), local(sp.fact, language)),
    }];
    // 英語・中国語は紹介の文だけ。追加の読みものは日本語版
    if language != Lang::Ja {
        return result;
    }
    result.push(Section { title: "なかまの体とくらし", body: profile(sp.art).to_string() });
    result.push(Section { title: "観察のコツ", body: tips(sp.beh).to_string() });
    let mut spots: Vec<usize> = life::places_of(e).into_iter().map(|p| p.0).collect();
    spots.dedup();
    let names: Vec<&str> = spots.iter().map(|&s| SPOTS[s].name.0).collect();
    result.push(Section {
        title: "関東で会うには",
        body: format!(
            "{}{}\n{}{}\n{}{}\n{}{}\n{}{}\n\n{}",
            ja("成虫が見られる季節："),
            {
                let (a, b) = sp.months;
                if (a, b) == (1, 12) { ja("一年じゅう（冬は集まってじっとしている）").to_string() } else if a == b { format!("{}月", a) } else { format!("{}月から{}月", a, b) }
            },
            ja("活動する時間帯："),
            {
                let names = ["早朝", "昼", "夕方", "夜"];
                if sp.times == 15 { ja("一日じゅう").to_string() } else { (0..4).filter(|t| sp.times & (1 << t) != 0).map(|t| names[t]).collect::<Vec<_>>().join("・") }
            },
            ja("活動しない時間は："),
            match sp.rest() {
                life::Rest::UnderLeaf => ja("葉の裏や草のかげで、はねを閉じてじっと休んでいる"),
                life::Rest::Roost => ja("草の茎や小枝の先にとまって、じっと休んでいる"),
                life::Rest::Trunk => ja("木の幹や枝にとまったまま、じっとしている"),
                life::Rest::Litter => ja("木の根元の落ち葉や土の中にもぐっている"),
                life::Rest::Hideout => ja("草の根元や石のかげにひそんでいる"),
                life::Rest::Nest => ja("巣の中や、巣の入り口で休んでいる"),
                life::Rest::WaterEdge => ja("岸の草や浮き葉のかげで休んでいる"),
            },
            ja("冬越し："),
            match sp.winter() {
                None => ja("関東では冬を越せず、毎年、南の国から海をわたって飛んでくる").to_string(),
                Some((stage, site)) => {
                    let st = match stage {
                        life::Stage::Egg => ja("たまご"),
                        life::Stage::EggCase => ja("たまごのかたまり（卵のう）"),
                        life::Stage::Yago => ja("幼虫（ヤゴ）"),
                        life::Stage::Chrysalis | life::Stage::Cocoon => ja("さなぎ"),
                        life::Stage::Adult => ja("成虫"),
                        _ => ja("幼虫"),
                    };
                    let si = match site {
                        life::Site::Soil => ja("土の中"),
                        life::Site::Litter => ja("落ち葉の下"),
                        life::Site::DeadWood => ja("朽ち木や枯れ木の中"),
                        life::Site::Stem => ja("草の茎や枝"),
                        life::Site::Bark => ja("木の幹や樹皮のすきま"),
                        life::Site::WaterBottom => ja("水の底"),
                        life::Site::Nest => ja("巣の中"),
                        life::Site::UnderStone => ja("石の下"),
                        life::Site::Bank => ja("水辺の岸の石や倒木の下・落ち葉の下"),
                        life::Site::InTrunk => ja("生きた木の幹の中"),
                        life::Site::LeafUnder => ja("冬も葉の落ちない木の葉の裏"),
                    };
                    format!("{}で、{}{}", st, si, ja("ですごす。成虫が見られない季節も、そこをさがせば見つかる"))
                }
            },
            ja("このゲームでは、次の場所で会えます："),
            names.join("、"),
            ja("活動しない時間帯の虫は、休んでいる場所をさがせば見つかります。動かないかわりに、葉や土にかくれていて見つけにくいので、近づいてズームで撮りましょう。虫は季節によって見られる時期が決まっています。地図の上の月の帯で季節を変えて、会いに行きましょう。季節は、成虫が見られるおおよその時期です。本当に観察に行くときは、暑さや虫刺されに気をつけ、草むらや林では長そで・長ズボンを着ましょう。立ち入り禁止の場所には入らず、公園や神社・お寺の決まりを守ってください。つかまえた虫は、観察が終わったら元の場所にそっと放しましょう。")
        ),
    });
    result
}

